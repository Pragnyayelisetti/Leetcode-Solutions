class Solution {
public:
    int countVowelStrings(int n) {
        //n=1 --> 5+0+0+0+0
        //n=2 --> 5+4+3+2+1
        //n=3 --> (5+4+3+2+1)+(4+3+2+1)+(3+2+1)+(2+1)+1
        //n=3 --> (5*1)+(4*2)+(3*3)+(2*4)+(1*5)
        //aaa , aae , aai , aao , aau , aee
        //n=4 --> 70
        //n=4 --> (5*1)+(4*3)+(3*6)+(2*10)+(1*15)
        //------>            +3+4+5
        //n=5 --> (5*1)+(4*4)+(3*10)+(2*20)+(1*35)
        //                   +6+10+15
        //n=6 --> (5*1)+(4*5)+(3*15)+(2*35)+(1*70)
        //5 , 15 , 35 , 70 , 126
        //2*3*4*5/24
        //3*4*5*6/24
        return (n+1)*(n+2)*(n+3)*(n+4)/24;
    }
};